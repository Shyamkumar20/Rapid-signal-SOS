import { supabase } from "@/lib/supabase";
import { OFFICIAL_PHONE, SERVICE_INFO, type Profile, type SosReport } from "@/lib/types";
import { agentBus } from "@/lib/agent-bus";
import { analyzeIncident, type IncidentIntel } from "@/lib/incident-intel";
import { formatLocationLine, lockExactLocation, type LockedLocation } from "@/lib/location-lock";
import { downloadAccidentWord } from "@/lib/word-report";
import { emergencyStore } from "@/lib/emergency-store";

export interface ArjunResult {
  success: boolean;
  error?: string;
  report?: SosReport;
  intel?: IncidentIntel;
  location?: LockedLocation | null;
  wordFile?: string;
  recipient: string;
  alertMessage: string;
}

let inFlight = false;

function buildAlertMessage(report: SosReport, intel: IncidentIntel, location: LockedLocation | null) {
  const loc = location ? formatLocationLine(location) : report.location_text;
  const maps = location?.mapsUrl || "";
  const services = report.dispatched_services
    .map((s) => `${SERVICE_INFO[s].label} ${SERVICE_INFO[s].number}`)
    .join(" + ");

  return `RAPID SIGNAL SOS — EMERGENCY ALERT
(Legal routing: 100/108/101 → ${OFFICIAL_PHONE})

FIR: ${report.id.slice(0, 8).toUpperCase()}
Type: ${intel.incidentType}
Severity: ${intel.severity.toUpperCase()}
Services: ${services}
Reporter: ${report.reporter_name} (${report.reporter_phone})
Location: ${loc}
Map: ${maps}
Summary: ${intel.summary}

Word FIR generated by ARJUN trained agent. Open the in-app emergency popup and downloaded document.`;
}

export function officialWhatsAppUrl(message: string) {
  const digits = OFFICIAL_PHONE.replace(/\D/g, "");
  return `https://wa.me/${digits}?text=${encodeURIComponent(message)}`;
}

export function officialSmsUrl(message: string) {
  const digits = OFFICIAL_PHONE.replace(/\D/g, "");
  return `sms:+${digits}?body=${encodeURIComponent(message.slice(0, 600))}`;
}

async function logDispatch(
  report: SosReport,
  intel: IncidentIntel,
  location: LockedLocation | null,
  message: string
) {
  try {
    const res = await fetch(`${import.meta.env.VITE_SUPABASE_URL}/functions/v1/dispatch-sos`, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        Authorization: `Bearer ${import.meta.env.VITE_SUPABASE_ANON_KEY}`,
      },
      body: JSON.stringify({
        report_id: report.id,
        incident_type: intel.incidentType,
        description: intel.summary,
        location_text: report.location_text,
        latitude: location?.lat ?? report.latitude,
        longitude: location?.lng ?? report.longitude,
        severity: intel.severity,
        reporter_name: report.reporter_name,
        reporter_phone: report.reporter_phone,
        services: intel.services,
      }),
    });
    if (res.ok) return;
  } catch {
    // fall through to local log
  }

  const logs = intel.services.map((svc) => ({
    report_id: report.id,
    service_type: svc,
    service_number: SERVICE_INFO[svc].number,
    recipient_phone: OFFICIAL_PHONE.replace(/\s/g, ""),
    message,
    status: "sent" as const,
  }));
  await supabase.from("dispatch_logs").insert(logs);
}

export async function runArjunPipeline(input: {
  profile: Profile | null;
  voiceHints?: {
    incident_type?: string;
    description?: string;
    location_text?: string;
    severity?: string;
    services?: string[];
  };
  fallbackCoords?: { lat: number; lng: number } | null;
}): Promise<ArjunResult> {
  if (inFlight) {
    return { success: false, error: "ARJUN is already filing a report.", recipient: OFFICIAL_PHONE, alertMessage: "" };
  }
  inFlight = true;

  try {
    const transcript = agentBus.getTranscriptText();
    const intel = analyzeIncident(transcript, input.voiceHints);
    const location = await lockExactLocation(input.fallbackCoords || agentBus.getCoords());
    const locationText =
      input.voiceHints?.location_text?.trim() ||
      (location ? formatLocationLine(location) : "Exact location unavailable — GPS denied");

    let clusterId = crypto.randomUUID();
    try {
      const { data: existingCluster } = await supabase
        .from("sos_reports")
        .select("id, cluster_id")
        .ilike("incident_type", intel.incidentType)
        .ilike("location_text", `%${locationText.slice(0, 40)}%`)
        .gte("created_at", new Date(Date.now() - 30 * 60 * 1000).toISOString())
        .limit(1)
        .maybeSingle();
      if (existingCluster?.cluster_id) clusterId = existingCluster.cluster_id;
    } catch {
      // continue
    }

    const isValidUUID = (str?: string | null) =>
      typeof str === "string" && /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(str);

    // Get current authenticated user ID or generate valid UUID
    const { data: authData } = await supabase.auth.getUser();
    let reporterId = authData?.user?.id;
    if (!isValidUUID(reporterId)) {
      reporterId = isValidUUID(input.profile?.id) ? input.profile!.id : crypto.randomUUID();
    }

    const reporterName = input.profile?.full_name || authData?.user?.user_metadata?.full_name || "Verified Citizen";
    const reporterPhone = input.profile?.phone || authData?.user?.user_metadata?.phone || "Citizen Phone";

    // Guarantee the profile row exists in the profiles table to satisfy foreign key constraint
    try {
      await supabase.from("profiles").upsert(
        {
          id: reporterId,
          full_name: reporterName,
          phone: reporterPhone,
          email: input.profile?.email || authData?.user?.email || null,
          created_at: new Date().toISOString(),
        },
        { onConflict: "id" }
      );
    } catch (profErr) {
      console.warn("Auto-profile upsert before SOS report:", profErr);
    }

    const { data: reportData, error: insertError } = await supabase
      .from("sos_reports")
      .insert({
        reporter_id: reporterId,
        reporter_name: reporterName,
        reporter_phone: reporterPhone,
        incident_type: intel.incidentType,
        description: intel.summary,
        location_text: locationText,
        latitude: location?.lat ?? null,
        longitude: location?.lng ?? null,
        severity: intel.severity,
        dispatched_services: intel.services,
        cluster_id: clusterId,
        status: "pending",
      })
      .select()
      .single();

    if (insertError) {
      console.error("SOS Report insert error:", insertError);
      throw new Error(`Database error: ${insertError.message}`);
    }

    const report = reportData as SosReport;
    const alertMessage = buildAlertMessage(report, intel, location);
    await logDispatch(report, intel, location, alertMessage);
    agentBus.markFiled();

    // Sync to unified EmergencyStore
    await emergencyStore.saveReport(report);

    const newReward = {
      id: crypto.randomUUID(),
      user_id: reporterId || crypto.randomUUID(),
      report_id: report.id,
      title: "Good Samaritan Recognition",
      description: `Recognized for reporting a ${intel.incidentType} incident via TARA + ARJUN.`,
      amount: 500,
      status: "pending" as const,
      awarded_at: null,
      created_at: new Date().toISOString(),
    };

    try {
      await supabase.from("rewards").insert(newReward);
    } catch (rewErr) {
      console.warn("Reward insert warning:", rewErr);
    }

    await emergencyStore.saveReward(newReward);

    const wordFile = await downloadAccidentWord({
      report,
      intel,
      location,
      transcript,
    });

    return {
      success: true,
      report,
      intel,
      location,
      wordFile,
      recipient: OFFICIAL_PHONE,
      alertMessage,
    };
  } catch (err) {
    return {
      success: false,
      error: err instanceof Error ? err.message : "ARJUN failed to file the report",
      recipient: OFFICIAL_PHONE,
      alertMessage: "",
    };
  } finally {
    inFlight = false;
  }
}
